# Regenerates engine/apmultitracker/area_crosscode.py from a checkout of the CrossCode PopTracker pack (MIT):
#   git clone https://github.com/lurch9229/CrossCode-Poptracker-AP pack
#   python tools/make-area-data.py pack engine/apmultitracker/area_crosscode.py $(git -C pack rev-parse --short HEAD)
import re, sys
pack, out, commit = sys.argv[1], sys.argv[2], sys.argv[3]
tab = open(f"{pack}/scripts/autotracking/tab_mapping.lua", encoding="utf-8").read()
locs = open(f"{pack}/scripts/autotracking/location_mapping.lua", encoding="utf-8").read()
def table(name):
    body = re.search(name + r"\s*=\s*\{(.*?)\n\}", tab, re.S).group(1)
    return dict(re.findall(r'\["([^"]+)"\]\s*=\s*"([^"]+)"', body))
regions, floors = table("REGION_MAPPING"), table("DUNGEON_MAPPING")
paths = {}
for lid, body in re.findall(r'^\[(\d+)\]\s*=\s*\{([^}]*)\}', locs, re.M):
    first = re.search(r'"@([^"]+)"', body)
    if not first:
        continue
    parts = first.group(1).split("/")
    if parts[0] in ("Shop Types", "Botanics"):
        continue
    paths[int(lid)] = "/".join(parts[:2])
lic = open(f"{pack}/LICENSE", encoding="utf-8").read().strip()
with open(out, "w", encoding="utf-8") as f:
    f.write('"""CrossCode area data, from the CrossCode PopTracker pack by lurch9229 (MIT licence):\n')
    f.write(f'https://github.com/lurch9229/CrossCode-Poptracker-AP (commit {commit}).\n')
    f.write('Generated by tools/make-area-data.py: area tab names (REGION_MAPPING, DUNGEON_MAPPING) and each location\'s\narea/sub-area (from LOCATION_MAPPING; shop types and botanics left out).\n\n')
    f.write(lic.replace('"""', "'''") + '\n"""\n\n')
    f.write(f"REGIONS = {regions!r}\n\nFLOORS = {floors!r}\n\nLOCATIONS = {{\n")
    for k in sorted(paths):
        f.write(f"    {k}: {paths[k]!r},\n")
    f.write("}\n")
print(len(regions), len(floors), len(paths))
