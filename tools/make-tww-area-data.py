# Regenerates engine/apmultitracker/area_tww.py from a checkout of Mysteryem's The Wind Waker PopTracker pack (MIT):
#   git clone https://github.com/Mysteryem/ww-poptracker pack
#   python tools/make-tww-area-data.py pack engine/apmultitracker/area_tww.py $(git -C pack rev-parse --short HEAD)
import re
import sys

pack, out, commit = sys.argv[1], sys.argv[2], sys.argv[3]
lua = open(f"{pack}/scripts/autotracking/archipelago.lua", encoding="utf-8").read()
body = re.search(r"local _STAGE_MAPPING = \{(.*?)\n\}\n", lua, re.S).group(1)
stages = {}
for tab, entries in re.findall(r'\{\s*"([^"]+)",\s*\{(.*?)\n\s*\}\s*\}', body, re.S):
    for line in entries.splitlines():
        line = line.split("--", 1)[0]
        m = re.search(r'\{"([^"]+)"(?:,\s*"([^"]+)")?\}', line)
        if m:
            stages[m.group(1)] = (tab, m.group(2) or "")
lic = open(f"{pack}/LICENSE", encoding="utf-8").read().strip()
with open(out, "w", encoding="utf-8") as f:
    f.write('"""The Wind Waker stage names, from Mysteryem\'s The Wind Waker PopTracker pack (MIT licence):\n')
    f.write(f"https://github.com/Mysteryem/ww-poptracker (commit {commit}).\n")
    f.write("Generated by tools/make-tww-area-data.py: stage name -> (map tab, the place it is, when it has one of its "
            "own).\n\n")
    f.write(lic.replace('"""', "'''") + '\n"""\n\n')
    f.write("STAGES = {\n")
    for k in sorted(stages):
        f.write(f"    {k!r}: {stages[k]!r},\n")
    f.write("}\n")
print(len(stages))
